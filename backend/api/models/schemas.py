# ─────────────────────────────────────────────────────────────────────────────
# Search Schemas
# ─────────────────────────────────────────────────────────────────────────────

class NLSearchRequest(BaseModel):
    query: str = Field(..., min_length=3, max_length=500)


class ProjectFilter(BaseModel):
    """Safe, parameterized filter object (never raw SQL from LLM)."""
    state_name: Optional[str] = None
    constituency_name: Optional[str] = None
    mp_name: Optional[str] = None
    risk_band: Optional[List[str]] = None
    min_risk_score: Optional[float] = None
    max_risk_score: Optional[float] = None
    min_amount_lakh: Optional[float] = None
    max_amount_lakh: Optional[float] = None
    min_age_days: Optional[int] = None
    max_age_days: Optional[int] = None
    is_overdue: Optional[bool] = None
    is_completed: Optional[bool] = None
    is_ongoing: Optional[bool] = None
    has_expenditure: Optional[bool] = None
    location_type: Optional[str] = None
    sort_by: str = "overall_risk_score"
    sort_order: str = "desc"
    page: int = 1
    page_size: int = 20


class NLSearchResponse(BaseModel):
    query: str
    interpreted_as: str       # human-readable interpretation
    filter_applied: ProjectFilter
    results: ProjectListResponse
    disclaimer: str = "Results are based on pattern matching. Verify data independently."


# ─────────────────────────────────────────────────────────────────────────────
# Generic Responses
# ─────────────────────────────────────────────────────────────────────────────

class HealthResponse(BaseModel):
    status: str
    database: str
    model_version: str
    rules_version: str
    total_projects: int
    timestamp: datetime


class ErrorResponse(BaseModel):
    error: str
    detail: Optional[str] = None
